from crewai import Agent, Task, Crew
from rag_tool import ChromaRAGTool
from dotenv import load_dotenv
import os
import httpx

from logging_config import configure_logging, get_logger

load_dotenv()
configure_logging()
logger = get_logger(__name__)

# Для прокси (если нужен)
http_client = httpx.Client(proxy=os.getenv("PROXY_URL")) if os.getenv("PROXY_URL") else None

# RAG-инструмент (общий для всех)
rag_tool = ChromaRAGTool()

# ========== 1. АГЕНТЫ ==========

analyst = Agent(
    role="AI Consultant",
    goal="Предлагать практичные и реалистичные AI-решения для бизнеса",
    backstory="""
    Вы опытный AI-консультант с глубокими знаниями в области внедрения искусственного интеллекта.
    Ваша задача — предлагать решения, которые реально работают в бизнесе, а не просто звучат красиво.
    Вы учитываете бюджет, сроки, технические ограничения и готовность компании к изменениям.
    Всегда опираетесь на проверенные кейсы и методологии.
    """,
    tools=[rag_tool],  # может искать кейсы
    llm="gpt-5.4-mini",
    verbose=True,
    http_client=http_client
)

researcher = Agent(
    role="AI Researcher",
    goal="Находить релевантные инструменты, технологии и бизнес-кейсы",
    backstory="""
    Вы исследователь AI-решений с доступом к базе знаний (ChromaDB) и интернету.
    Ваша суперсила — находить самые актуальные инструменты, библиотеки, API и реальные примеры внедрения.
    Вы всегда даёте конкретные названия, ссылки и факты, а не общие фразы.
    """,
    tools=[rag_tool],
    llm="gpt-5.4-mini",
    verbose=True,
    http_client=http_client
)

critic = Agent(
    role="AI Critic",
    goal="Проверять реалистичность, выявлять риски и слабые места предложений",
    backstory="""
    Вы критик AI-решений с острым взглядом на подводные камни.
    Ваша задача — найти все возможные проблемы до того, как клиент столкнётся с ними в реальности.
    Вы проверяете:
    - Бюджетную реалистичность
    - Техническую выполнимость
    - Готовность данных
    - Скрытые затраты (поддержка, дообучение, интеграция)
    - Риски безопасности и соответствия регуляторным требованиям
    Вы всегда объективны, конструктивны и честны, даже если это означает сказать "это пока нереализуемо".
    """,
    llm="gpt-5.4-mini",  # у критика может не быть инструментов, только логика
    verbose=True,
    http_client=http_client
)


# ========== 2. ЗАДАЧИ ==========

def create_tasks(query: str):
    """
    Создаёт три задачи для трёх агентов
    """

    task_research = Task(
        description=f"""
        Клиент спрашивает: {query}

        Используй инструмент Business Cases Search, чтобы найти релевантные кейсы, инструменты и методологии.
        Выдели:
        1. Какие инструменты и технологии использовались в похожих проектах?
        2. Какие были результаты и метрики?
        3. Какие сложности возникали при внедрении?

        Дай конкретные названия, цифры и ссылки на кейсы.
        """,
        expected_output="""
        Список релевантных инструментов, технологий и примеров внедрения с конкретными деталями.
        """,
        agent=researcher
    )

    task_analysis = Task(
        description=f"""
        На основе исследования {task_research.expected_output} предложи AI-решение для бизнеса.

        Твой ответ должен включать:
        1. **Основное предложение**: какая AI-технология подходит?
        2. **Почему это решит проблему**: связь с бизнес-целью клиента
        3. **Примерная архитектура**: из каких компонентов состоит решение
        4. **Ожидаемые результаты**: метрики, KPI, сроки
        5. **Следующие шаги**: с чего начать внедрение (пилотный проект)

        Опирайся на кейсы из исследования, но адаптируй под ситуацию клиента.
        """,
        expected_output="""
        Практичное AI-решение с обоснованием, архитектурой, метриками и планом внедрения.
        """,
        agent=analyst,
        context=[task_research]
    )

    task_critique = Task(
        description=f"""
        Проанализируй предложение консультанта ({task_analysis.expected_output}) и найди слабые места.

        Оцени по следующим критериям:

        **1. Бюджетная реалистичность**
        - Какие скрытые затраты могут возникнуть? (поддержка, дообучение, API-ключи, cloud-ресурсы)

        **2. Техническая выполнимость**
        - Достаточно ли у компании данных нужного качества и объёма?
        - Есть ли у команды нужные навыки или потребуется наём/аутсорс?

        **3. Риски внедрения**
        - Что может пойти не так в процессе интеграции?
        - Как долго может занять реальное внедрение (не обещанные, а реальные сроки)?

        **4. Альтернативы**
        - Есть ли более простое/дешёвое решение, которое даст 80% результата за 20% усилий?

        **5. Compliance & безопасность**
        - Какие риски для данных клиента? (GDPR, ФЗ-152, утечки)

        Дай чёткий вердикт: **ГОТОВО К ВНЕДРЕНИЮ**, **НУЖНЫ ДОРАБОТКИ** или **НЕ РЕКОМЕНДУЕТСЯ**.
        Если «доработки» — укажи конкретные шаги для улучшения.
        """,
        expected_output="""
        Детальный критический анализ с баллами рисков и итоговым вердиктом.
        """,
        agent=critic,
        context=[task_research, task_analysis]
    )

    return [task_research, task_analysis, task_critique]


# ========== 3. ФУНКЦИЯ ЗАПУСКА ==========

def run_consultation(query: str) -> str:
    """Запускает полную консультацию с тремя агентами"""
    tasks = create_tasks(query)
    crew = Crew(
        agents=[researcher, analyst, critic],
        tasks=tasks,
        verbose=True  # можно поставить False, чтобы бот не писал в терминал каждый шаг
    )
    result = crew.kickoff()
    return str(result)


# ========== 4. ТЕСТ ==========
if __name__ == "__main__":
    result = run_consultation("Как автоматизировать обработку клиентских запросов в службе поддержки?")
    logger.info("consultation_demo_result", result=result)
